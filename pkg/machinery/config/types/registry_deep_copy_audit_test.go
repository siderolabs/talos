// TestRegistryDeepCopyAudit walks every registered document kind, seeds every
// reachable meta size field with a parsed value, clones the document and
// asserts that the clone does not share the size's internal buffers.
//
// The deep copy code is generated by siderolabs/deep-copy, which copies
// unexported fields of a foreign package's type only if that type has its own
// DeepCopy method. The size types do, but the generator only finds it when the
// field is declared with the type's own name: a field declared through the
// backwards-compatibility alias in config/types/block resolves to a
// *types.Alias, which the generator neither recognizes as a method holder nor
// treats as foreign, so it silently emits a shallow struct copy instead.
//
// That failure mode is invisible at the call site and produces working code, so
// it is asserted here for every document rather than left to per-package tests.
// New documents are picked up automatically.
func TestRegistryDeepCopyAudit(t *testing.T) {
	t.Parallel()

	kinds := registry.Kinds()
	require.NotEmpty(t, kinds, "no document kinds registered, blank imports in types.go are missing")

	for _, kind := range kinds {
		t.Run(kind, func(t *testing.T) {
			t.Parallel()

			// a Size holds either a byte size or a percentage, and each arm of its
			// DeepCopy has to be walked: seeding only one leaves the other untested.
			for _, mode := range []seedMode{seedBytes, seedPercent} {
				t.Run(mode.String(), func(t *testing.T) {
					t.Parallel()

					doc, err := registry.New(kind, "v1alpha1")
					require.NoError(t, err)

					original := findSizeFields(reflect.ValueOf(doc), "", mode)
					if len(original) == 0 {
						return
					}

					// the clone is walked read-only: seeding it would hand it fresh
					// buffers and hide the very aliasing this test looks for.
					clone := findSizeFields(reflect.ValueOf(doc.Clone()), "", seedNone)
					require.Len(t, clone, len(original), "clone of %q has a different shape than the original", kind)

					for i, field := range original {
						assert.Equal(t, field.path, clone[i].path)

						if field.raw != nil {
							// a clone which dropped the size would otherwise compare
							// non-nil against nil and pass.
							require.NotNil(t, clone[i].raw,
								"%s.%s lost its raw buffer in the clone", kind, field.path)
							assert.NotSame(t, field.raw, clone[i].raw,
								"%s.%s shares its raw buffer with the original: declare the field as meta.%s, not through the block alias",
								kind, field.path, field.kind)
						}

						if field.value != nil {
							require.NotNil(t, clone[i].value,
								"%s.%s lost its value pointer in the clone", kind, field.path)
							assert.NotSame(t, field.value, clone[i].value,
								"%s.%s shares its value pointer with the original: declare the field as meta.%s, not through the block alias",
								kind, field.path, field.kind)
						}
					}
				})
			}
		})
	}
}

// seedMode selects the value a size leaf is seeded with, or that the walk is
// read-only.
type seedMode int

const (
	// seedNone walks without touching anything: used for the clone.
	seedNone seedMode = iota
	// seedBytes seeds every size leaf with a byte size.
	seedBytes
	// seedPercent seeds Size leaves with a percentage; a leaf typed as ByteSize
	// has no percentage form and keeps the byte value.
	seedPercent
)

func (m seedMode) String() string {
	switch m {
	case seedNone:
		return "none"
	case seedBytes:
		return "bytes"
	case seedPercent:
		return "percent"
	default:
		return "unknown"
	}
}

func (m seedMode) seeds() bool {
	return m != seedNone
}

// sizeField is a single seeded size leaf, with the addresses of the internals
// that a shallow copy would share.
type sizeField struct {
	path  string
	kind  string
	raw   *byte
	value *uint64
}

var (
	byteSizeType       = reflect.TypeFor[meta.ByteSize]()
	percentageSizeType = reflect.TypeFor[meta.PercentageSize]()
	sizeType           = reflect.TypeFor[meta.Size]()
)

// sizeFieldOf seeds v (one of the three meta size types) according to mode, and
// returns the addresses of its internals. It returns (nil, false) when v is not
// a size type at all.
//
//nolint:gocyclo
func sizeFieldOf(v reflect.Value, path string, mode seedMode) ([]sizeField, bool) {
	switch v.Type() {
	case byteSizeType:
		if mode.seeds() {
			v.Set(reflect.ValueOf(meta.MustByteSize("4GiB")))
		}

		return []sizeField{internalsOf(v, path, "ByteSize")}, true
	case percentageSizeType:
		if mode.seeds() {
			v.Set(reflect.ValueOf(*meta.MustSize("80%").PercentageSize))
		}

		return []sizeField{internalsOf(v, path, "PercentageSize")}, true
	case sizeType:
		switch mode {
		case seedBytes:
			v.Set(reflect.ValueOf(meta.MustSize("4GiB")))
		case seedPercent:
			v.Set(reflect.ValueOf(meta.MustSize("80%")))
		case seedNone:
		}

		if inner := v.FieldByName("ByteSize"); !inner.IsNil() {
			return []sizeField{internalsOf(inner.Elem(), path, "Size")}, true
		}

		if inner := v.FieldByName("PercentageSize"); !inner.IsNil() {
			return []sizeField{internalsOf(inner.Elem(), path, "Size")}, true
		}

		return []sizeField{{path: path, kind: "Size"}}, true
	default:
		return nil, false
	}
}

// internalsOf reads the unexported value/raw fields of a seeded size value.
// Tests are the only place that needs to see them, hence the unsafe read.
func internalsOf(v reflect.Value, path, kind string) sizeField {
	out := sizeField{path: path, kind: kind}

	raw := readUnexported(v, "raw").Bytes()
	if len(raw) > 0 {
		out.raw = &raw[0]
	}

	if value := readUnexported(v, "value"); !value.IsNil() {
		out.value = (*uint64)(value.UnsafePointer())
	}

	return out
}

func readUnexported(v reflect.Value, name string) reflect.Value {
	f := v.FieldByName(name)

	return reflect.NewAt(f.Type(), unsafe.Pointer(f.UnsafeAddr())).Elem()
}

// findSizeFields walks v the same way findSecretFields does (instantiating nil
// pointers, growing empty slices and maps) and seeds every size leaf it reaches.
//
//nolint:gocyclo,cyclop
func findSizeFields(v reflect.Value, path string, mode seedMode) []sizeField {
	const maxDepth = 8

	if strings.Count(path, ".")+strings.Count(path, "[0]") > maxDepth {
		return nil
	}

	//nolint:exhaustive // only pointer/slice/map/struct are traversed, everything else returns nil.
	switch v.Kind() {
	case reflect.Pointer:
		if v.IsNil() {
			if !mode.seeds() || !v.CanSet() {
				return nil
			}

			v.Set(reflect.New(v.Type().Elem()))
		}

		return findSizeFields(v.Elem(), path, mode)

	case reflect.Slice:
		elemType := v.Type().Elem()
		if elemType.Kind() != reflect.Struct && !(elemType.Kind() == reflect.Pointer && elemType.Elem().Kind() == reflect.Struct) {
			return nil
		}

		if v.Len() == 0 {
			if !mode.seeds() || !v.CanSet() {
				return nil
			}

			v.Set(reflect.Append(v, reflect.New(elemType).Elem()))
		}

		return findSizeFields(v.Index(0), path+"[0]", mode)

	case reflect.Map:
		elemType := v.Type().Elem()
		if elemType.Kind() != reflect.Pointer || elemType.Elem().Kind() != reflect.Struct {
			return nil
		}

		if v.IsNil() {
			if !mode.seeds() || !v.CanSet() {
				return nil
			}

			v.Set(reflect.MakeMap(v.Type()))
		}

		key := reflect.New(v.Type().Key()).Elem()
		if key.Kind() != reflect.String {
			return nil
		}

		key.SetString("audit")

		entry := v.MapIndex(key)

		if mode.seeds() {
			entry = reflect.New(elemType.Elem())
			v.SetMapIndex(key, entry)
		}

		if !entry.IsValid() || entry.IsNil() {
			return nil
		}

		return findSizeFields(entry, path+`["audit"]`, mode)

	case reflect.Struct:
		if !isTalosType(v.Type()) {
			return nil
		}

		var out []sizeField

		for i := range v.NumField() {
			field := v.Type().Field(i)
			if !field.IsExported() {
				continue
			}

			tagName := yamlTagName(field.Tag.Get("yaml"))
			fieldPath := path

			switch {
			case field.Anonymous:
				// Embedded struct (e.g., meta.Meta), recurse without extending path.
			case tagName == "" || tagName == "-":
				continue
			default:
				if fieldPath != "" {
					fieldPath += "."
				}

				fieldPath += tagName
			}

			fv := v.Field(i)

			if sizes, ok := sizeFieldOf(fv, fieldPath, mode); ok {
				out = append(out, sizes...)

				continue
			}

			out = append(out, findSizeFields(fv, fieldPath, mode)...)
		}

		return out

	default:
		return nil
	}
}
