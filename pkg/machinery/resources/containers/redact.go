package containers

import (
	"github.com/cosi-project/runtime/pkg/resource"

	"github.com/siderolabs/talos/pkg/machinery/redactable"
)

// The environment, the entrypoint and the arguments of a container are copied out of the machine
// configuration verbatim, and the ContainerConfig document says as much: whatever is put there is as
// sensitive as the machine configuration itself.
//
// The redaction is hand-written rather than generated by redactgen, because all three are lists of
// "key=value" strings: dropping them, which is all a struct tag can say, would leave nothing to read,
// while keeping the keys and taking out the values still tells the reader how the container is run.

// Check interfaces.
var (
	_ redactable.Spec = &ContainerSpecSpec{}
	_ redactable.Spec = &ContainerInstanceSpecSpec{}
)

// HasSecrets implements redactable.Spec interface.
func (spec *ContainerSpecSpec) HasSecrets(resource.Metadata) bool {
	return redactable.HasKeyValues(spec.Environment) || redactable.HasKeyValues(spec.Entrypoint) || redactable.HasKeyValues(spec.Args)
}

// RedactSecrets implements redactable.Spec interface.
func (spec *ContainerSpecSpec) RedactSecrets(resource.Metadata) {
	spec.Environment = redactable.RedactKeyValues(spec.Environment)
	spec.Entrypoint = redactable.RedactKeyValues(spec.Entrypoint)
	spec.Args = redactable.RedactKeyValues(spec.Args)
}

// HasSecrets implements redactable.Spec interface.
func (spec *ContainerInstanceSpecSpec) HasSecrets(resource.Metadata) bool {
	return redactable.HasKeyValues(spec.Environment) || redactable.HasKeyValues(spec.Entrypoint) || redactable.HasKeyValues(spec.Args)
}

// RedactSecrets implements redactable.Spec interface.
func (spec *ContainerInstanceSpecSpec) RedactSecrets(resource.Metadata) {
	spec.Environment = redactable.RedactKeyValues(spec.Environment)
	spec.Entrypoint = redactable.RedactKeyValues(spec.Entrypoint)
	spec.Args = redactable.RedactKeyValues(spec.Args)
}
