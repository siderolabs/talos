// The control plane resources carry what the machine configuration put into the extra arguments, the
// environment variables and the extra manifest headers, so they have to be assumed to hold secrets,
// and the rendered static pod carries all of it once more.
//
// The redaction here is hand-written rather than generated by redactgen, because these specs do not
// hold a set of sensitive fields but a set of names paired with values. Blanking a whole field, which
// is all a struct tag can say, would leave nothing to read; keeping the names and taking out the
// values leaves the resource useful for working out how the control plane is configured, which is
// what a non-admin reads it for.
//
// The kubelet resources are redacted the same way: the extra arguments of the machine configuration
// and the rendered command line lose their values, while the kubelet configuration and the image
// credential provider configuration keep everything but the few values which carry a credential.

// Check interfaces.
var (
	_ redactable.Spec = &AdmissionControlConfigSpec{}
	_ redactable.Spec = &APIServerConfigSpec{}
	_ redactable.Spec = &ControllerManagerConfigSpec{}
	_ redactable.Spec = &SchedulerConfigSpec{}
	_ redactable.Spec = &ExtraManifestsConfigSpec{}
	_ redactable.Spec = &ManifestSpec{}
	_ redactable.Spec = &StaticPodSpec{}
	_ redactable.Spec = &KubeletConfigSpec{}
	_ redactable.Spec = &KubeletSpecSpec{}
)

// HasSecrets implements redactable.Spec interface.
func (spec *AdmissionControlConfigSpec) HasSecrets(resource.Metadata) bool {
	return slices.ContainsFunc(spec.Config, func(plugin AdmissionPluginSpec) bool {
		return len(plugin.Configuration) > 0
	})
}

// RedactSecrets implements redactable.Spec interface.
func (spec *AdmissionControlConfigSpec) RedactSecrets(resource.Metadata) {
	spec.Config = xslices.Map(spec.Config, func(plugin AdmissionPluginSpec) AdmissionPluginSpec {
		// the configuration of a plugin is a free-form document out of the machine configuration --
		// a webhook kubeconfig among the things which end up there -- so there is no telling which of
		// its keys are safe to show, and the whole of it goes. The plugin names stay, which is what
		// tells the reader which admission plugins the API server is configured with.
		plugin.Configuration = nil

		return plugin
	})
}

// HasSecrets implements redactable.Spec interface.
func (spec *APIServerConfigSpec) HasSecrets(resource.Metadata) bool {
	return hasArgValues(spec.ExtraArgs) || redactable.HasKeyValues(spec.Args) || len(spec.EnvironmentVariables) > 0
}

// RedactSecrets implements redactable.Spec interface.
func (spec *APIServerConfigSpec) RedactSecrets(resource.Metadata) {
	spec.ExtraArgs = redactArgValues(spec.ExtraArgs)
	spec.Args = redactable.RedactKeyValues(spec.Args)
	spec.EnvironmentVariables = redactMapValues(spec.EnvironmentVariables)
}

// HasSecrets implements redactable.Spec interface.
func (spec *ControllerManagerConfigSpec) HasSecrets(resource.Metadata) bool {
	return hasArgValues(spec.ExtraArgs) || redactable.HasKeyValues(spec.Args) || len(spec.EnvironmentVariables) > 0
}

// RedactSecrets implements redactable.Spec interface.
func (spec *ControllerManagerConfigSpec) RedactSecrets(resource.Metadata) {
	spec.ExtraArgs = redactArgValues(spec.ExtraArgs)
	spec.Args = redactable.RedactKeyValues(spec.Args)
	spec.EnvironmentVariables = redactMapValues(spec.EnvironmentVariables)
}

// HasSecrets implements redactable.Spec interface.
func (spec *SchedulerConfigSpec) HasSecrets(resource.Metadata) bool {
	return hasArgValues(spec.ExtraArgs) || redactable.HasKeyValues(spec.Args) || len(spec.EnvironmentVariables) > 0 || len(spec.Config) > 0
}

// RedactSecrets implements redactable.Spec interface.
func (spec *SchedulerConfigSpec) RedactSecrets(resource.Metadata) {
	spec.ExtraArgs = redactArgValues(spec.ExtraArgs)
	spec.Args = redactable.RedactKeyValues(spec.Args)
	spec.EnvironmentVariables = redactMapValues(spec.EnvironmentVariables)

	// the scheduler configuration is a free-form document out of the machine configuration: there is
	// no telling which of its keys are safe to show, so the whole of it goes
	spec.Config = nil
}

// HasSecrets implements redactable.Spec interface.
func (spec *ExtraManifestsConfigSpec) HasSecrets(resource.Metadata) bool {
	for _, manifest := range spec.ExtraManifests {
		if len(manifest.ExtraHeaders) > 0 || manifest.InlineManifest != "" || hasURLUserinfo(manifest.URL) {
			return true
		}
	}

	return false
}

// RedactSecrets implements redactable.Spec interface.
func (spec *ExtraManifestsConfigSpec) RedactSecrets(resource.Metadata) {
	spec.ExtraManifests = xslices.Map(spec.ExtraManifests, func(manifest ExtraManifest) ExtraManifest {
		// the headers are how a manifest download authenticates itself: the documented example is an
		// Authorization bearer token
		manifest.ExtraHeaders = redactMapValues(manifest.ExtraHeaders)
		manifest.URL = redactURLUserinfo(manifest.URL)

		if manifest.InlineManifest != "" {
			// an inline manifest is a Kubernetes object out of the machine configuration, and a
			// Secret is one of the things which end up there
			manifest.InlineManifest = constants.Redacted
		}

		return manifest
	})
}

// HasSecrets implements redactable.Spec interface.
func (spec *ManifestSpec) HasSecrets(resource.Metadata) bool {
	for _, item := range spec.Items {
		if _, redacted := redactManifestObject(item.Object); redacted {
			return true
		}
	}

	return false
}

// RedactSecrets implements redactable.Spec interface.
func (spec *ManifestSpec) RedactSecrets(resource.Metadata) {
	spec.Items = xslices.Map(spec.Items, func(item SingleManifest) SingleManifest {
		item.Object, _ = redactManifestObject(item.Object)

		return item
	})
}

// HasSecrets implements redactable.Spec interface.
func (spec *StaticPodSpec) HasSecrets(resource.Metadata) bool {
	_, redacted := redactPodValues(spec.Pod)

	return redacted
}

// RedactSecrets implements redactable.Spec interface.
func (spec *StaticPodSpec) RedactSecrets(resource.Metadata) {
	spec.Pod, _ = redactPodValues(spec.Pod)
}

// HasSecrets implements redactable.Spec interface.
func (spec *KubeletConfigSpec) HasSecrets(resource.Metadata) bool {
	_, configRedacted := redactKubeletConfig(spec.ExtraConfig)
	_, credentialProviderRedacted := redactCredentialProviderConfig(spec.CredentialProviderConfig)

	return hasArgValues(spec.ExtraArgs) || configRedacted || credentialProviderRedacted
}

// RedactSecrets implements redactable.Spec interface.
func (spec *KubeletConfigSpec) RedactSecrets(resource.Metadata) {
	spec.ExtraArgs = redactArgValues(spec.ExtraArgs)
	spec.ExtraConfig, _ = redactKubeletConfig(spec.ExtraConfig)
	spec.CredentialProviderConfig, _ = redactCredentialProviderConfig(spec.CredentialProviderConfig)
}

// HasSecrets implements redactable.Spec interface.
func (spec *KubeletSpecSpec) HasSecrets(resource.Metadata) bool {
	_, configRedacted := redactKubeletConfig(spec.Config)
	_, credentialProviderRedacted := redactCredentialProviderConfig(spec.CredentialProviderConfig)

	return redactable.HasKeyValues(spec.Args) || configRedacted || credentialProviderRedacted
}

// RedactSecrets implements redactable.Spec interface.
func (spec *KubeletSpecSpec) RedactSecrets(resource.Metadata) {
	spec.Args = redactable.RedactKeyValues(spec.Args)
	spec.Config, _ = redactKubeletConfig(spec.Config)
	spec.CredentialProviderConfig, _ = redactCredentialProviderConfig(spec.CredentialProviderConfig)
}

// hasArgValues reports whether any of the extra arguments carries a value.
func hasArgValues(args map[string]ArgValues) bool {
	for _, values := range args {
		if len(values.Values) > 0 {
			return true
		}
	}

	return false
}

// redactArgValues returns a copy of the extra arguments with every value replaced, keeping the flags.
func redactArgValues(args map[string]ArgValues) map[string]ArgValues {
	if len(args) == 0 {
		return args
	}

	out := make(map[string]ArgValues, len(args))

	for flag, values := range args {
		out[flag] = ArgValues{
			Values: xslices.Map(values.Values, func(string) string { return constants.Redacted }),
		}
	}

	return out
}

// redactMapValues returns a copy of the map with every value replaced, keeping the keys.
func redactMapValues(m map[string]string) map[string]string {
	if len(m) == 0 {
		return m
	}

	out := make(map[string]string, len(m))

	for key := range m {
		out[key] = constants.Redacted
	}

	return out
}

// hasURLUserinfo reports whether the URL carries credentials.
func hasURLUserinfo(rawURL string) bool {
	parsed, err := url.Parse(rawURL)

	return err == nil && parsed.User != nil
}

// redactURLUserinfo replaces the password in the URL, keeping the rest of it readable.
func redactURLUserinfo(rawURL string) string {
	parsed, err := url.Parse(rawURL)
	if err != nil || parsed.User == nil {
		return rawURL
	}

	parsed.User = url.UserPassword(parsed.User.Username(), constants.Redacted)

	return parsed.String()
}

// redactKubeletConfig returns the kubelet configuration with the values of the static pod URL headers
// replaced, and reports whether it replaced anything.
//
// Unlike the scheduler configuration, the kubelet configuration is a single well-known document
// (KubeletConfiguration), and the headers sent along with the static pod URL request are the only
// place in it which carries a credential: the rest -- the reservations, the eviction thresholds, the
// feature gates -- is what the resource is read for, so it stays. The header names stay as well.
//
// The configuration is not redacted in place, see redactPodValues.
func redactKubeletConfig(config map[string]any) (map[string]any, bool) {
	headers, ok := config["staticPodURLHeader"].(map[string]any)
	if !ok || len(headers) == 0 {
		return config, false
	}

	redactedHeaders := make(map[string]any, len(headers))

	for name, values := range headers {
		if list, ok := values.([]any); ok {
			redactedHeaders[name] = xslices.Map(list, func(any) any { return constants.Redacted })
		} else {
			redactedHeaders[name] = constants.Redacted
		}
	}

	out := maps.Clone(config)
	out["staticPodURLHeader"] = redactedHeaders

	return out, true
}

// redactCredentialProviderConfig returns the image credential provider configuration with the values
// of the provider environment variables and command line flags replaced, and reports whether it
// replaced anything.
//
// A provider (CredentialProviderConfig.providers) is an executable run the way a container is: the env
// list of name/value pairs and the args are the only values it carries which may hold a credential, and
// they have the same shape as in a container, so the container redaction covers them. The provider
// names and the images they match stay.
//
// The configuration is not redacted in place, see redactPodValues.
func redactCredentialProviderConfig(config map[string]any) (map[string]any, bool) {
	providers, ok := config["providers"].([]any)
	if !ok {
		return config, false
	}

	redactedProviders, redacted := redactContainers(providers)
	if !redacted {
		return config, false
	}

	out := maps.Clone(config)
	out["providers"] = redactedProviders

	return out, true
}

// redactManifestObject returns the manifest with everything but the fields which name the object
// taken out, and reports whether it took anything out.
//
// A manifest is a Kubernetes object rendered out of the machine configuration, and an inline manifest
// is whatever the user put there -- a Secret among the rest -- so there is no telling which of its
// fields are safe to show. What is left is enough to tell which objects Talos applies, without any of
// their contents: the annotations go too, as a manifest applied earlier carries its whole previous
// version in one of them.
func redactManifestObject(object map[string]any) (map[string]any, bool) {
	out := make(map[string]any, 3)

	for _, key := range []string{"apiVersion", "kind"} {
		if value, ok := object[key]; ok {
			out[key] = value
		}
	}

	redacted := false

	if metadata, ok := object["metadata"].(map[string]any); ok {
		redactedMetadata := make(map[string]any, 2)

		for _, key := range []string{"name", "namespace"} {
			if value, ok := metadata[key]; ok {
				redactedMetadata[key] = value
			}
		}

		out["metadata"] = redactedMetadata
		redacted = len(redactedMetadata) != len(metadata)
	}

	return out, redacted || len(out) != len(object)
}

// redactPodValues returns the pod manifest with the values of the container environment variables and
// of the command line flags replaced, and reports whether it replaced anything.
//
// The manifest is rendered from the control plane config resources, so it carries the extra arguments
// and the environment variables of the machine configuration once more, this time in a shape no struct
// tag can reach.
//
// Nothing is redacted in place: the generated deep copy of the spec copies only the top-level map (see
// DeepCopy in deep_copy.generated.go), so everything below it is shared with the resource kept in the
// state, and writing into it would redact that one too. Every level along the way is copied instead,
// and the branches which are left alone stay shared, which is safe as long as nothing writes to them.
func redactPodValues(pod map[string]any) (map[string]any, bool) {
	podSpec, ok := pod["spec"].(map[string]any)
	if !ok {
		return pod, false
	}

	out := podSpec
	redacted := false

	for _, key := range []string{"initContainers", "containers"} {
		containers, ok := podSpec[key].([]any)
		if !ok {
			continue
		}

		redactedContainers, changed := redactContainers(containers)
		if !changed {
			continue
		}

		if !redacted {
			out = maps.Clone(podSpec)
			redacted = true
		}

		out[key] = redactedContainers
	}

	if !redacted {
		return pod, false
	}

	redactedPod := maps.Clone(pod)
	redactedPod["spec"] = out

	return redactedPod, true
}

// redactContainers redacts the values of every container in the list.
func redactContainers(containers []any) ([]any, bool) {
	out := containers
	redacted := false

	for idx, item := range containers {
		container, ok := item.(map[string]any)
		if !ok {
			continue
		}

		redactedContainer, changed := redactContainer(container)
		if !changed {
			continue
		}

		if !redacted {
			out = slices.Clone(containers)
			redacted = true
		}

		out[idx] = redactedContainer
	}

	return out, redacted
}

// redactContainer redacts the environment variables and the command line of a single container.
func redactContainer(container map[string]any) (map[string]any, bool) {
	out := container
	redacted := false

	if env, ok := container["env"].([]any); ok {
		if redactedEnv, changed := redactPodEnv(env); changed {
			out = maps.Clone(container)
			out["env"] = redactedEnv
			redacted = true
		}
	}

	for _, key := range []string{"command", "args"} {
		args, ok := container[key].([]any)
		if !ok {
			continue
		}

		redactedArgs, changed := redactPodArgs(args)
		if !changed {
			continue
		}

		if !redacted {
			out = maps.Clone(container)
			redacted = true
		}

		out[key] = redactedArgs
	}

	return out, redacted
}

// redactPodEnv replaces the value of every environment variable, keeping the names.
func redactPodEnv(env []any) ([]any, bool) {
	out := env
	redacted := false

	for idx, item := range env {
		variable, ok := item.(map[string]any)
		if !ok {
			continue
		}

		if value, ok := variable["value"].(string); !ok || value == "" {
			continue
		}

		if !redacted {
			out = slices.Clone(env)
			redacted = true
		}

		redactedVariable := maps.Clone(variable)
		redactedVariable["value"] = constants.Redacted

		out[idx] = redactedVariable
	}

	return out, redacted
}

// redactPodArgs replaces the value of every "--flag=value" in the container command line.
func redactPodArgs(args []any) ([]any, bool) {
	out := args
	redacted := false

	for idx, item := range args {
		arg, ok := item.(string)
		if !ok {
			continue
		}

		redactedArg, changed := redactable.RedactKeyValue(arg)
		if !changed {
			continue
		}

		if !redacted {
			out = slices.Clone(args)
			redacted = true
		}

		out[idx] = redactedArg
	}

	return out, redacted
}
