// GeneratedRecoveryKeyType is type of GeneratedRecoveryKey resource.
const GeneratedRecoveryKeyType = resource.Type("GeneratedRecoveryKeys.secrets.talos.dev")

// GeneratedRecoveryKey holds a disk encryption recovery key generated by the node, until the operator fetches it.
//
// The resource ID is the volume ID. It is created by the volume manager when the recovery key slot is enrolled,
// and destroyed via the API once the operator fetched the key.
type GeneratedRecoveryKey = typed.Resource[GeneratedRecoveryKeySpec, GeneratedRecoveryKeyExtension]

// GeneratedRecoveryKeySpec describes the generated recovery key.
//
//gotagsrewrite:gen
type GeneratedRecoveryKeySpec struct {
	Key []byte `yaml:"key" protobuf:"1"`
}

// NewGeneratedRecoveryKey initializes a GeneratedRecoveryKey resource.
func NewGeneratedRecoveryKey(volumeID resource.ID) *GeneratedRecoveryKey {
	return typed.NewResource[GeneratedRecoveryKeySpec, GeneratedRecoveryKeyExtension](
		resource.NewMetadata(NamespaceName, GeneratedRecoveryKeyType, volumeID, resource.VersionUndefined),
		GeneratedRecoveryKeySpec{},
	)
}

// GeneratedRecoveryKeyExtension provides auxiliary methods for GeneratedRecoveryKey.
type GeneratedRecoveryKeyExtension struct{}

// ResourceDefinition implements meta.ResourceDefinitionProvider interface.
func (GeneratedRecoveryKeyExtension) ResourceDefinition() meta.ResourceDefinitionSpec {
	return meta.ResourceDefinitionSpec{
		Type:             GeneratedRecoveryKeyType,
		Aliases:          []resource.Type{},
		DefaultNamespace: NamespaceName,
		Sensitivity:      meta.Sensitive,
	}
}

func init() {
	proto.RegisterDefaultTypes()

	err := protobuf.RegisterDynamic[GeneratedRecoveryKeySpec](GeneratedRecoveryKeyType, &GeneratedRecoveryKey{})
	if err != nil {
		panic(err)
	}
}
