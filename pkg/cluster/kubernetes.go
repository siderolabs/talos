package cluster

import (
	"context"
	"fmt"
	"net"
	"net/netip"
	"net/url"
	"strconv"
	"strings"

	"k8s.io/client-go/kubernetes"
	"k8s.io/client-go/rest"
	"k8s.io/client-go/tools/clientcmd"
	clientcmdapi "k8s.io/client-go/tools/clientcmd/api"

	"github.com/siderolabs/talos/pkg/kubeconfig"
	k8s "github.com/siderolabs/talos/pkg/kubernetes"
	"github.com/siderolabs/talos/pkg/machinery/constants"
)

// KubernetesClient provides Kubernetes client built via Talos API Kubeconfig.
type KubernetesClient struct {
	// Base Talos client provider.
	ClientProvider

	// ForceEndpoint overrides default Kubernetes API endpoint.
	ForceEndpoint string

	KubeHelper *k8s.Client

	kubeconfig []byte
	clientset  *kubernetes.Clientset
}

// Kubeconfig returns raw kubeconfig.
//
// Kubeconfig is cached.
func (k *KubernetesClient) Kubeconfig(ctx context.Context) ([]byte, error) {
	if k.kubeconfig != nil {
		return k.kubeconfig, nil
	}

	client, err := k.Client()
	if err != nil {
		return nil, err
	}

	kubeconfigBytes, err := client.Kubeconfig(ctx)
	if err != nil {
		return nil, err
	}

	// the kubeconfig comes from the node, so it is untrusted input: make sure it is
	// a plain kubeconfig as generated by Talos before it is used or written out.
	if _, err = kubeconfig.LoadAndValidate(kubeconfigBytes); err != nil {
		return nil, err
	}

	k.kubeconfig = kubeconfigBytes

	return k.kubeconfig, nil
}

// K8sRestConfig returns *rest.Config (parsed kubeconfig).
func (k *KubernetesClient) K8sRestConfig(ctx context.Context) (*rest.Config, error) {
	kubeconfig, err := k.Kubeconfig(ctx)
	if err != nil {
		return nil, err
	}

	config, err := clientcmd.BuildConfigFromKubeconfigGetter("", func() (*clientcmdapi.Config, error) {
		return clientcmd.Load(kubeconfig)
	})
	if err != nil {
		return nil, err
	}

	if err = ApplyKubernetesEndpointOverride(config, k.ForceEndpoint); err != nil {
		return nil, err
	}

	return config, nil
}

// ValidateKubernetesEndpoint checks that the endpoint has the format accepted by ApplyKubernetesEndpointOverride.
//
// The accepted format is [https://]host[:port][/], where host is a hostname, an IPv4 address,
// or an IPv6 address (in brackets if a port is specified).
func ValidateKubernetesEndpoint(endpoint string) error {
	_, err := parseKubernetesEndpoint(endpoint)

	return err
}

// ApplyKubernetesEndpointOverride overrides the Kubernetes API endpoint in the config.
//
// If endpoint is empty, the config is left unchanged. If the endpoint
// doesn't specify a port, the default control plane port is used.
func ApplyKubernetesEndpointOverride(config *rest.Config, endpoint string) error {
	if endpoint == "" {
		return nil
	}

	hostPort, err := parseKubernetesEndpoint(endpoint)
	if err != nil {
		return err
	}

	config.Host = hostPort

	return nil
}

// parseKubernetesEndpoint parses the endpoint in the format [https://]host[:port][/] and returns host:port.
func parseKubernetesEndpoint(endpoint string) (string, error) {
	invalid := func(reason string) error {
		return fmt.Errorf("invalid Kubernetes endpoint %q: %s, expected format is [https://]host[:port]", endpoint, reason)
	}

	// Plain IP address without brackets and port
	addr, err := netip.ParseAddr(endpoint)
	if err == nil {
		return netip.AddrPortFrom(addr, constants.DefaultControlPlanePort).String(), nil
	}

	stripped, _ := strings.CutPrefix(endpoint, "https://")
	if strings.Contains(stripped, "://") {
		return "", invalid("only the https:// scheme is supported")
	}

	u, err := url.Parse("https://" + stripped)
	if err != nil {
		return "", invalid(err.Error())
	}

	if u.Hostname() == "" {
		return "", invalid("host is empty")
	}

	if u.Port() != "" {
		portNum, err := strconv.Atoi(u.Port())
		if err != nil || portNum < 1 || portNum >= 1<<16 {
			return "", invalid(fmt.Sprintf("invalid port \"%q\"", u.Port()))
		}
	} else {
		// add default port when an url is given without a port number
		u.Host = net.JoinHostPort(u.Hostname(), strconv.Itoa(constants.DefaultControlPlanePort))
	}

	return u.String(), nil
}

// K8sClient builds Kubernetes client via Talos Kubeconfig API.
//
// Kubernetes client instance is cached.
func (k *KubernetesClient) K8sClient(ctx context.Context) (*kubernetes.Clientset, error) {
	if k.clientset != nil {
		return k.clientset, nil
	}

	config, err := k.K8sRestConfig(ctx)
	if err != nil {
		return nil, err
	}

	if k.KubeHelper, err = k8s.NewForConfig(config); err != nil {
		return nil, err
	}

	k.clientset = k.KubeHelper.Clientset

	return k.clientset, nil
}

// K8sHelper returns wrapper around K8sClient.
func (k *KubernetesClient) K8sHelper(ctx context.Context) (*k8s.Client, error) {
	if k.KubeHelper != nil {
		return k.KubeHelper, nil
	}

	_, err := k.K8sClient(ctx)
	if err != nil {
		return nil, err
	}

	return k.KubeHelper, nil
}

// K8sClose closes Kubernetes client.
func (k *KubernetesClient) K8sClose() error {
	if k.KubeHelper == nil {
		return nil
	}

	return k.KubeHelper.Close()
}
