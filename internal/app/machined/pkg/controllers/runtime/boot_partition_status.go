// BootPartitionStatusController publishes the partition the machine was booted from.
//
// The boot partition is discovered from the `talos.boot.partuuid` kernel argument (set by the GRUB config
// generated by Talos, and by Talos on kexec), falling back to the `LoaderDevicePartUUID` EFI variable (set by
// sd-boot/systemd-stub to the ESP it was loaded from). If neither is available, the resource is not created.
//
// The volume manager waits for the boot partition to be discovered before declaring the system volumes
// missing: the disk the machine was booted from certainly exists, it might just be slow to enumerate.
type BootPartitionStatusController struct {
	V1Alpha1Mode machineruntime.Mode

	// ReadEFIBootPartitionUUID reads the boot partition UUID from the EFI variables, defaults to reading
	// `LoaderDevicePartUUID`. It returns uuid.Nil if the variable is not available.
	ReadEFIBootPartitionUUID func() (uuid.UUID, error)
}

// Name implements controller.Controller interface.
func (ctrl *BootPartitionStatusController) Name() string {
	return "runtime.BootPartitionStatusController"
}

// Inputs implements controller.Controller interface.
func (ctrl *BootPartitionStatusController) Inputs() []controller.Input {
	return []controller.Input{
		{
			Namespace: runtimeres.NamespaceName,
			Type:      runtimeres.KernelCmdlineType,
			ID:        optional.Some(runtimeres.KernelCmdlineID),
			Kind:      controller.InputWeak,
		},
	}
}

// Outputs implements controller.Controller interface.
func (ctrl *BootPartitionStatusController) Outputs() []controller.Output {
	return []controller.Output{
		{
			Type: runtimeres.BootPartitionStatusType,
			Kind: controller.OutputExclusive,
		},
	}
}

// Run implements controller.Controller interface.
func (ctrl *BootPartitionStatusController) Run(ctx context.Context, r controller.Runtime, logger *zap.Logger) error {
	// in container mode we don't own the devices
	if ctrl.V1Alpha1Mode == machineruntime.ModeContainer {
		return nil
	}

	for {
		select {
		case <-ctx.Done():
			return nil
		case <-r.EventCh():
		}

		partitionUUID, source, err := ctrl.detect(ctx, r, logger)
		if err != nil {
			return err
		}

		if source == "" {
			// not enough information yet
			continue
		}

		if partitionUUID == uuid.Nil {
			logger.Debug("boot partition is not known")

			return nil
		}

		if err = safe.WriterModify(ctx, r, runtimeres.NewBootPartitionStatus(runtimeres.NamespaceName, runtimeres.BootPartitionStatusID),
			func(status *runtimeres.BootPartitionStatus) error {
				status.TypedSpec().PartitionUUID = partitionUUID.String()

				return nil
			}); err != nil {
			return fmt.Errorf("error updating boot partition status: %w", err)
		}

		logger.Info("boot partition detected", zap.String("partition_uuid", partitionUUID.String()), zap.String("source", source))

		// the boot partition doesn't change while the machine is running, so we're done
		return nil
	}
}

// detect returns the boot partition UUID and the source it was detected from.
//
// An empty source means that the detection should be retried once more inputs are available,
// while uuid.Nil with a non-empty source means that the boot partition is not known.
//
// The kernel argument takes precedence over the EFI variable: it is set by Talos on kexec, when the bootloader
// is skipped and the `LoaderDevicePartUUID` EFI variable (which can't be updated from the OS) is stale,
// e.g. still points to the ISO the machine was installed from.
func (ctrl *BootPartitionStatusController) detect(ctx context.Context, r controller.Reader, logger *zap.Logger) (uuid.UUID, string, error) {
	kernelCmdline, err := safe.ReaderGetByID[*runtimeres.KernelCmdline](ctx, r, runtimeres.KernelCmdlineID)
	if err != nil {
		if state.IsNotFoundError(err) {
			return uuid.Nil, "", nil
		}

		return uuid.Nil, "", fmt.Errorf("error getting kernel cmdline: %w", err)
	}

	if value := procfs.NewCmdline(kernelCmdline.TypedSpec().Cmdline).Get(constants.KernelParamBootPartitionUUID).First(); value != nil {
		partitionUUID, parseErr := uuid.Parse(*value)
		if parseErr == nil {
			return partitionUUID, "cmdline", nil
		}

		logger.Warn("error parsing the boot partition UUID from the kernel cmdline", zap.String("value", *value), zap.Error(parseErr))
	}

	partitionUUID, err := ctrl.readEFIBootPartitionUUID()
	if err != nil {
		logger.Warn("error reading the boot partition UUID from EFI variables", zap.Error(err))
	}

	if partitionUUID != uuid.Nil {
		return partitionUUID, "efi", nil
	}

	return uuid.Nil, "none", nil
}

func (ctrl *BootPartitionStatusController) readEFIBootPartitionUUID() (uuid.UUID, error) {
	if ctrl.ReadEFIBootPartitionUUID != nil {
		return ctrl.ReadEFIBootPartitionUUID()
	}

	return readLoaderDevicePartUUID()
}

// readLoaderDevicePartUUID reads the `LoaderDevicePartUUID` EFI variable, returning uuid.Nil if the machine
// is not booted via UEFI or the variable is not set (i.e. the bootloader is not sd-boot).
func readLoaderDevicePartUUID() (uuid.UUID, error) {
	if _, err := os.Stat(constants.EFIVarsMountPoint); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return uuid.Nil, nil
		}

		return uuid.Nil, err
	}

	rw, err := efivarfs.NewFilesystemReaderWriter(false)
	if err != nil {
		return uuid.Nil, err
	}

	defer rw.Close() //nolint:errcheck

	partitionUUID, err := efivarfs.ReadLoaderDevicePartUUID(rw)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return uuid.Nil, nil
		}

		return uuid.Nil, err
	}

	return partitionUUID, nil
}
