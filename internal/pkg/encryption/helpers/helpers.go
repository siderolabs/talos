// Package helpers defines encryption handlers.
package helpers

import (
	"context"

	"github.com/siderolabs/talos/pkg/machinery/resources/hardware"
)

// SystemInformationGetter defines the closure which can be used in key handlers to get the node UUID.
type SystemInformationGetter func(context.Context) (*hardware.SystemInformation, error)

// TPMLockFunc is a function that ensures that the TPM is locked and PCR state is as expected.
type TPMLockFunc func(context.Context, func() error) error

// SaltGetter defines the closure which can be used in key handlers to get the encryption salt.
type SaltGetter func(context.Context) ([]byte, error)

// RecoveryKeyGetter returns the operator-supplied recovery key for the volume.
//
// The second return value is false if no key was supplied (yet).
type RecoveryKeyGetter func(ctx context.Context, volumeID string) ([]byte, bool, error)

// RecoveryKeyPublisher hands a freshly generated recovery key for the volume over to the operator-facing side.
//
// The key is generated by the node when the recovery slot gets enrolled, and the operator has to fetch it once.
type RecoveryKeyPublisher func(ctx context.Context, volumeID string, key []byte) error
