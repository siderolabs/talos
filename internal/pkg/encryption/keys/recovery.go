package keys

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"io"

	"github.com/siderolabs/go-blockdevice/v2/encryption"
	"github.com/siderolabs/go-blockdevice/v2/encryption/luks"
	"github.com/siderolabs/go-blockdevice/v2/encryption/token"

	"github.com/siderolabs/talos/internal/pkg/encryption/helpers"
)

// RecoveryToken is the userdata stored in the partition token metadata for the recovery key slot.
type RecoveryToken struct {
	KeySlots []int `json:"keyslots"`
	// Fetched is set once the operator fetched the generated key.
	//
	// Until then the key is regenerated whenever the volume is unlocked with another key,
	// so a key nobody knows never stays enrolled.
	Fetched bool `json:"fetched"`
}

// RecoveryKeyHandler handles a key which is held by the operator and never stored on the node.
//
// The key is generated by the node when the slot is enrolled (which happens while the volume
// is unlocked with another key, so no key material is needed from the operator), and published
// for the operator to fetch once. When unlocking, the handler never blocks waiting for the key:
// if the operator hasn't supplied it, GetKey returns ErrKeyNotAvailable right away, so the slot
// is skipped and the volume manager retries once the key is supplied.
type RecoveryKeyHandler struct {
	KeyHandler

	volumeID  string
	getter    helpers.RecoveryKeyGetter
	publisher helpers.RecoveryKeyPublisher
}

// NewRecoveryKeyHandler creates new RecoveryKeyHandler.
//
// The getter supplies the operator-provided key for unlocking, the publisher hands generated keys over
// to the operator. Either might be nil, in which case the respective operation is not available.
func NewRecoveryKeyHandler(key KeyHandler, volumeID string, getter helpers.RecoveryKeyGetter, publisher helpers.RecoveryKeyPublisher) *RecoveryKeyHandler {
	return &RecoveryKeyHandler{
		KeyHandler: key,
		volumeID:   volumeID,
		getter:     getter,
		publisher:  publisher,
	}
}

// NewKey implements Handler interface.
//
// A new random key is generated and published for the operator; the token marks it as not fetched yet.
func (h *RecoveryKeyHandler) NewKey(ctx context.Context) (*encryption.Key, token.Token, error) {
	if h.publisher == nil {
		return nil, nil, ErrKeyNotAvailable
	}

	raw := make([]byte, 32)
	if _, err := io.ReadFull(rand.Reader, raw); err != nil {
		return nil, nil, fmt.Errorf("failed to generate recovery key: %w", err)
	}

	// base64, so the key can be typed in on the console
	key := []byte(base64.StdEncoding.EncodeToString(raw))

	if err := h.publisher(ctx, h.volumeID, key); err != nil {
		return nil, nil, fmt.Errorf("failed to publish generated recovery key for volume %q: %w", h.volumeID, err)
	}

	return encryption.NewKey(h.slot, key), &luks.Token[*RecoveryToken]{
		Type: TokenTypeRecovery,
		UserData: &RecoveryToken{
			KeySlots: []int{h.slot},
			Fetched:  false,
		},
	}, nil
}

// GetKey implements Handler interface.
//
// The operator-supplied key is returned if there is one. Otherwise an enrolled key which was never
// fetched is reported as invalid (its token says so), so it gets regenerated; a fetched one is
// simply not available.
func (h *RecoveryKeyHandler) GetKey(ctx context.Context, t token.Token) (*encryption.Key, error) {
	if h.getter != nil {
		key, ok, err := h.getter(ctx, h.volumeID)
		if err != nil {
			return nil, fmt.Errorf("failed to get recovery key for volume %q: %w", h.volumeID, err)
		}

		if ok {
			return encryption.NewKey(h.slot, key), nil
		}
	}

	if recoveryToken, ok := t.(*luks.Token[*RecoveryToken]); ok && !recoveryToken.UserData.Fetched {
		return nil, fmt.Errorf("%w: recovery key was never fetched by the operator", ErrTokenInvalid)
	}

	return nil, ErrKeyNotAvailable
}
