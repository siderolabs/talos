const (
	// marker is the doc comment which marks a struct as requiring the RedactSecrets method.
	marker = "//redactgen:gen"
	// tagKey is the struct tag key which marks a field as sensitive.
	tagKey = "redact"

	// strategyReplace replaces the value with constants.Redacted (strings) or redacts the
	// password part of the URL (url.URL).
	strategyReplace = "replace"
	// strategyZero resets the value to the zero value of its type.
	strategyZero = "zero"

	resourcePkgPath  = "github.com/cosi-project/runtime/pkg/resource"
	resourcesPkgPath = "github.com/siderolabs/talos/pkg/machinery/resources"
	constantsPkgPath = "github.com/siderolabs/talos/pkg/machinery/constants"
	urlPkgPath       = "net/url"
)

// options control the generated output.
type options struct {
	// outputFile is the base name of the generated file: the declarations coming from it are
	// ignored when checking for the identifier conflicts.
	outputFile string
	// header is the boilerplate to put at the top of the generated file.
	header string
	// commandLine is recorded in the "Code generated by" comment.
	commandLine string
}

// generate produces the contents of the generated file, or nil if the package has nothing marked for generation.
func generate(pkg *packages.Package, opts options) ([]byte, error) {
	g := &generator{
		pkg:        pkg,
		opts:       opts,
		memo:       map[types.Type]bool{},
		inProgress: map[types.Type]bool{},
		imports:    map[string]struct{}{},
		queued:     map[string]struct{}{},
	}

	return g.run()
}

type generator struct {
	pkg  *packages.Package
	opts options

	// memoization of containsSecrets, see the comment there for the cycle handling.
	memo       map[types.Type]bool
	inProgress map[types.Type]bool
	cycles     int

	imports map[string]struct{}

	// pending is the queue of the types to generate the helpers for, queued keeps the type
	// names which were queued already.
	pending []*types.Named
	queued  map[string]struct{}

	methods bytes.Buffer
	helpers bytes.Buffer
	asserts []string
}

func (g *generator) run() ([]byte, error) {
	marked, err := g.markedTypes()
	if err != nil {
		return nil, err
	}

	if len(marked) == 0 {
		return nil, nil
	}

	g.imports[resourcePkgPath] = struct{}{}
	g.imports[resourcesPkgPath] = struct{}{}

	for _, named := range marked {
		if err = g.emitMethod(named); err != nil {
			return nil, err
		}
	}

	// emitting the helpers might queue more types (nested structs), so keep going until the queue drains
	for len(g.pending) > 0 {
		named := g.pending[0]
		g.pending = g.pending[1:]

		if err = g.emitHelpers(named); err != nil {
			return nil, err
		}
	}

	return g.format()
}

// markedTypes returns the types marked with the marker comment, sorted by name.
//
//nolint:gocyclo
func (g *generator) markedTypes() ([]*types.Named, error) {
	var marked []*types.Named

	for _, file := range g.pkg.Syntax {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}

			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}

				if !hasMarker(genDecl.Doc) && !hasMarker(typeSpec.Doc) {
					continue
				}

				obj := g.pkg.Types.Scope().Lookup(typeSpec.Name.Name)
				if obj == nil {
					return nil, fmt.Errorf("type %s marked with %s is not found in the package scope", typeSpec.Name.Name, marker)
				}

				named, ok := obj.Type().(*types.Named)
				if !ok {
					return nil, fmt.Errorf("type %s marked with %s is not a named type", typeSpec.Name.Name, marker)
				}

				if _, ok = named.Underlying().(*types.Struct); !ok {
					return nil, fmt.Errorf("type %s marked with %s is not a struct", typeSpec.Name.Name, marker)
				}

				marked = append(marked, named)
			}
		}
	}

	slices.SortFunc(marked, func(a, b *types.Named) int {
		return strings.Compare(a.Obj().Name(), b.Obj().Name())
	})

	return marked, nil
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}

	return slices.ContainsFunc(doc.List, func(c *ast.Comment) bool {
		return c.Text == marker
	})
}

// emitMethod generates the RedactSecrets method for a marked type.
func (g *generator) emitMethod(named *types.Named) error {
	name := named.Obj().Name()

	g.asserts = append(g.asserts, fmt.Sprintf("_ resources.RedactableSpec[%s] = %s{}", name, name))

	if !g.containsSecrets(named) {
		fmt.Fprintf(&g.methods, passthroughMethodTemplate, name)

		return nil
	}

	if !hasDeepCopy(named) {
		return fmt.Errorf("type %s carries sensitive fields, but has no DeepCopy method: add it to the deep-copy generator invocation", name)
	}

	helper, err := g.helperFor(named, name)
	if err != nil {
		return err
	}

	fmt.Fprintf(&g.methods, redactMethodTemplate, name, helper)

	return nil
}

const passthroughMethodTemplate = `// RedactSecrets implements resources.RedactableSpec interface.
func (spec %[1]s) RedactSecrets(resource.Metadata) %[1]s {
	// no sensitive fields
	return spec
}

`

const redactMethodTemplate = `// RedactSecrets implements resources.RedactableSpec interface.
func (spec %[1]s) RedactSecrets(resource.Metadata) %[1]s {
	if !hasSecrets%[2]s(&spec) {
		return spec
	}

	// the spec might share the backing storage with the resource, so copy before mutating
	spec = spec.DeepCopy()

	redact%[2]s(&spec)

	return spec
}

`

// emitHelpers generates the hasSecrets/redact helper pair for a struct type carrying sensitive fields.
func (g *generator) emitHelpers(named *types.Named) error {
	name := named.Obj().Name()

	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("type %s is not a struct", name)
	}

	var checks, redacts []string

	for i := range st.NumFields() {
		field := st.Field(i)

		code, err := g.fieldCode("spec."+field.Name(), field.Type(), reflect.StructTag(st.Tag(i)).Get(tagKey), name+"."+field.Name())
		if err != nil {
			return err
		}

		checks = append(checks, code.check...)
		redacts = append(redacts, code.redact...)
	}

	if len(checks) == 0 {
		return fmt.Errorf("type %s has no sensitive fields, but helpers were requested for it", name)
	}

	fmt.Fprintf(&g.helpers, hasSecretsTemplate, name, indent(strings.Join(checks, "\n\n")))
	fmt.Fprintf(&g.helpers, redactTemplate, name, indent(strings.Join(redacts, "\n\n")))

	return nil
}

const hasSecretsTemplate = `// hasSecrets%[1]s checks if %[1]s carries any sensitive value.
func hasSecrets%[1]s(spec *%[1]s) bool {
%[2]s

	return false
}

`

const redactTemplate = `// redact%[1]s redacts sensitive values in %[1]s in place.
func redact%[1]s(spec *%[1]s) {
%[2]s
}

`

// fieldCode is the code generated for a single struct field.
type fieldCode struct {
	// check are the statements for the hasSecrets helper, they return true if the field carries a secret.
	check []string
	// redact are the statements for the redact helper.
	redact []string
}

//nolint:gocyclo,cyclop
func (g *generator) fieldCode(expr string, typ types.Type, tag, path string) (fieldCode, error) {
	if tag != "" {
		return g.leafCode(expr, typ, tag, path)
	}

	if !g.containsSecrets(typ) {
		return fieldCode{}, nil
	}

	switch underlying := typ.Underlying().(type) {
	case *types.Struct:
		helper, err := g.helperFor(typ, path)
		if err != nil {
			return fieldCode{}, err
		}

		return fieldCode{
			check:  []string{fmt.Sprintf("if hasSecrets%s(&%s) {\n\treturn true\n}", helper, expr)},
			redact: []string{fmt.Sprintf("redact%s(&%s)", helper, expr)},
		}, nil
	case *types.Pointer:
		helper, err := g.structHelperFor(underlying.Elem(), path)
		if err != nil {
			return fieldCode{}, err
		}

		return fieldCode{
			check:  []string{fmt.Sprintf("if %s != nil && hasSecrets%s(%s) {\n\treturn true\n}", expr, helper, expr)},
			redact: []string{fmt.Sprintf("if %s != nil {\n\tredact%s(%s)\n}", expr, helper, expr)},
		}, nil
	case *types.Slice:
		return g.collectionCode(expr, underlying.Elem(), path, true)
	case *types.Array:
		return g.collectionCode(expr, underlying.Elem(), path, true)
	case *types.Map:
		return g.collectionCode(expr, underlying.Elem(), path, false)
	default:
		return fieldCode{}, fmt.Errorf("%s: unsupported type %s carrying sensitive fields", path, typ)
	}
}

// collectionCode generates the code for a slice, an array or a map of structs (or pointers to structs).
//
// Slices and arrays are indexable, so the elements are redacted in place, while the map values are not
// addressable and have to be redacted as a copy which is put back into the map.
func (g *generator) collectionCode(expr string, elem types.Type, path string, indexable bool) (fieldCode, error) {
	if pointer, ok := elem.Underlying().(*types.Pointer); ok {
		helper, err := g.structHelperFor(pointer.Elem(), path)
		if err != nil {
			return fieldCode{}, err
		}

		return fieldCode{
			check:  []string{fmt.Sprintf("for _, item := range %s {\n\tif item != nil && hasSecrets%s(item) {\n\t\treturn true\n\t}\n}", expr, helper)},
			redact: []string{fmt.Sprintf("for _, item := range %s {\n\tif item != nil {\n\t\tredact%s(item)\n\t}\n}", expr, helper)},
		}, nil
	}

	helper, err := g.structHelperFor(elem, path)
	if err != nil {
		return fieldCode{}, err
	}

	if indexable {
		return fieldCode{
			check:  []string{fmt.Sprintf("for idx := range %s {\n\tif hasSecrets%s(&%s[idx]) {\n\t\treturn true\n\t}\n}", expr, helper, expr)},
			redact: []string{fmt.Sprintf("for idx := range %s {\n\tredact%s(&%s[idx])\n}", expr, helper, expr)},
		}, nil
	}

	return fieldCode{
		check:  []string{fmt.Sprintf("for _, item := range %s {\n\tif hasSecrets%s(&item) {\n\t\treturn true\n\t}\n}", expr, helper)},
		redact: []string{fmt.Sprintf("for key, item := range %s {\n\tredact%s(&item)\n\n\t%s[key] = item\n}", expr, helper, expr)},
	}, nil
}

// leafCode generates the code for a field marked with the redact tag.
func (g *generator) leafCode(expr string, typ types.Type, tag, path string) (fieldCode, error) {
	switch tag {
	case strategyReplace:
		return g.replaceCode(expr, typ, path)
	case strategyZero:
		return zeroCode(expr, typ, path)
	default:
		return fieldCode{}, fmt.Errorf("%s: unknown redact strategy %q (supported: %q, %q)", path, tag, strategyReplace, strategyZero)
	}
}

func (g *generator) replaceCode(expr string, typ types.Type, path string) (fieldCode, error) {
	if isURL(typ) || isURLPointer(typ) {
		g.imports[urlPkgPath] = struct{}{}
		g.imports[constantsPkgPath] = struct{}{}

		cond := fmt.Sprintf("%s.User != nil", expr)
		if isURLPointer(typ) {
			cond = fmt.Sprintf("%s != nil && %s.User != nil", expr, expr)
		}

		return fieldCode{
			check: []string{fmt.Sprintf("if %s {\n\treturn true\n}", cond)},
			redact: []string{
				fmt.Sprintf("if %s {\n\t%s.User = url.UserPassword(%s.User.Username(), constants.Redacted)\n}", cond, expr, expr),
			},
		}, nil
	}

	if basic, ok := typ.Underlying().(*types.Basic); ok && basic.Info()&types.IsString != 0 {
		g.imports[constantsPkgPath] = struct{}{}

		return fieldCode{
			check:  []string{fmt.Sprintf("if %s != \"\" {\n\treturn true\n}", expr)},
			redact: []string{fmt.Sprintf("if %s != \"\" {\n\t%s = constants.Redacted\n}", expr, expr)},
		}, nil
	}

	return fieldCode{}, fmt.Errorf("%s: redact:%q is not supported for type %s (supported: string kinds, url.URL, *url.URL), use redact:%q instead",
		path, strategyReplace, typ, strategyZero)
}

//nolint:gocyclo
func zeroCode(expr string, typ types.Type, path string) (fieldCode, error) {
	var cond, zero string

	switch underlying := typ.Underlying().(type) {
	case *types.Basic:
		switch {
		case underlying.Info()&types.IsString != 0:
			cond, zero = fmt.Sprintf("%s != \"\"", expr), `""`
		case underlying.Info()&types.IsBoolean != 0:
			cond, zero = expr, "false"
		case underlying.Info()&types.IsNumeric != 0:
			cond, zero = fmt.Sprintf("%s != 0", expr), "0"
		default:
			return fieldCode{}, fmt.Errorf("%s: redact:%q is not supported for type %s", path, strategyZero, typ)
		}
	case *types.Slice, *types.Map:
		cond, zero = fmt.Sprintf("len(%s) > 0", expr), "nil"
	case *types.Pointer, *types.Interface, *types.Signature, *types.Chan:
		cond, zero = fmt.Sprintf("%s != nil", expr), "nil"
	default:
		return fieldCode{}, fmt.Errorf("%s: redact:%q is not supported for type %s", path, strategyZero, typ)
	}

	return fieldCode{
		check:  []string{fmt.Sprintf("if %s {\n\treturn true\n}", cond)},
		redact: []string{fmt.Sprintf("if %s {\n\t%s = %s\n}", cond, expr, zero)},
	}, nil
}

// structHelperFor is helperFor with an additional check that the type is a struct.
func (g *generator) structHelperFor(typ types.Type, path string) (string, error) {
	if _, ok := typ.Underlying().(*types.Struct); !ok {
		return "", fmt.Errorf("%s: unsupported type %s carrying sensitive fields", path, typ)
	}

	return g.helperFor(typ, path)
}

// helperFor returns the name of the type to build the helper names from, queuing the helpers for generation.
func (g *generator) helperFor(typ types.Type, path string) (string, error) {
	named, ok := typ.(*types.Named)
	if !ok {
		return "", fmt.Errorf("%s: anonymous struct types carrying sensitive fields are not supported", path)
	}

	if named.TypeParams() != nil || named.TypeArgs() != nil {
		return "", fmt.Errorf("%s: generic type %s carrying sensitive fields is not supported", path, named)
	}

	obj := named.Obj()

	if obj.Pkg() == nil || obj.Pkg().Path() != g.pkg.PkgPath {
		return "", fmt.Errorf("%s: type %s carrying sensitive fields is declared in another package, redactgen only handles types of %s",
			path, named, g.pkg.PkgPath)
	}

	name := obj.Name()

	if _, ok = g.queued[name]; ok {
		return name, nil
	}

	for _, conflict := range []string{"hasSecrets" + name, "redact" + name} {
		if g.declaredElsewhere(conflict) {
			return "", fmt.Errorf("%s: generated helper %s conflicts with an existing declaration", path, conflict)
		}
	}

	g.queued[name] = struct{}{}
	g.pending = append(g.pending, named)

	return name, nil
}

// declaredElsewhere checks if the identifier is declared in the package outside of the generated file.
func (g *generator) declaredElsewhere(name string) bool {
	obj := g.pkg.Types.Scope().Lookup(name)
	if obj == nil {
		return false
	}

	return filepath.Base(g.pkg.Fset.Position(obj.Pos()).Filename) != g.opts.outputFile
}

// containsSecrets checks if the type (transitively) has any field marked with the redact tag.
func (g *generator) containsSecrets(typ types.Type) bool {
	if result, ok := g.memo[typ]; ok {
		return result
	}

	if g.inProgress[typ] {
		// a recursive type: going around the cycle can't discover any new fields
		g.cycles++

		return false
	}

	g.inProgress[typ] = true
	cyclesBefore := g.cycles

	result := g.scan(typ)

	delete(g.inProgress, typ)

	// the result is only conclusive if it wasn't cut short by a cycle
	if g.cycles == cyclesBefore {
		g.memo[typ] = result
	}

	return result
}

func (g *generator) scan(typ types.Type) bool {
	switch underlying := typ.Underlying().(type) {
	case *types.Struct:
		for i := range underlying.NumFields() {
			if reflect.StructTag(underlying.Tag(i)).Get(tagKey) != "" {
				return true
			}

			if g.containsSecrets(underlying.Field(i).Type()) {
				return true
			}
		}

		return false
	case *types.Pointer:
		return g.containsSecrets(underlying.Elem())
	case *types.Slice:
		return g.containsSecrets(underlying.Elem())
	case *types.Array:
		return g.containsSecrets(underlying.Elem())
	case *types.Map:
		return g.containsSecrets(underlying.Elem())
	default:
		return false
	}
}

// hasDeepCopy checks that the type has a `DeepCopy() T` method.
func hasDeepCopy(named *types.Named) bool {
	obj, _, _ := types.LookupFieldOrMethod(named, false, named.Obj().Pkg(), "DeepCopy")

	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}

	signature, ok := fn.Type().(*types.Signature)
	if !ok {
		return false
	}

	return signature.Params().Len() == 0 && signature.Results().Len() == 1 && types.Identical(signature.Results().At(0).Type(), named)
}

func isURL(typ types.Type) bool {
	named, ok := typ.(*types.Named)
	if !ok {
		return false
	}

	obj := named.Obj()

	return obj.Pkg() != nil && obj.Pkg().Path() == urlPkgPath && obj.Name() == "URL"
}

func isURLPointer(typ types.Type) bool {
	pointer, ok := typ.Underlying().(*types.Pointer)

	return ok && isURL(pointer.Elem())
}

func indent(code string) string {
	lines := strings.Split(code, "\n")

	for i, line := range lines {
		if line != "" {
			lines[i] = "\t" + line
		}
	}

	return strings.Join(lines, "\n")
}

// format assembles the file and runs it through gofmt.
func (g *generator) format() ([]byte, error) {
	var buf bytes.Buffer

	if g.opts.header != "" {
		buf.WriteString(strings.TrimRight(g.opts.header, "\n"))
		buf.WriteString("\n\n")
	}

	fmt.Fprintf(&buf, "// Code generated by %q; DO NOT EDIT.\n\npackage %s\n\n", g.opts.commandLine, g.pkg.Name)

	g.writeImports(&buf)

	fmt.Fprintf(&buf, "var (\n%s\n)\n\n", indent(strings.Join(g.asserts, "\n")))

	buf.Write(g.methods.Bytes())
	buf.Write(g.helpers.Bytes())

	source, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format the generated code: %w\n\n%s", err, buf.String())
	}

	return source, nil
}

// writeImports writes the imports in three groups: stdlib, external and Talos.
func (g *generator) writeImports(buf *bytes.Buffer) {
	groups := make([][]string, 3)

	for path := range g.imports {
		switch {
		case !strings.Contains(path, "."):
			groups[0] = append(groups[0], path)
		case strings.HasPrefix(path, "github.com/siderolabs/talos/"):
			groups[2] = append(groups[2], path)
		default:
			groups[1] = append(groups[1], path)
		}
	}

	buf.WriteString("import (\n")

	first := true

	for _, group := range groups {
		if len(group) == 0 {
			continue
		}

		if !first {
			buf.WriteString("\n")
		}

		first = false

		slices.Sort(group)

		for _, path := range group {
			fmt.Fprintf(buf, "\t%q\n", path)
		}
	}

	buf.WriteString(")\n\n")
}
